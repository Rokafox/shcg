    def effect_after_taking_damage(self, damage_amount: int, game_state: SHCGGameState, draw_ui, set_text, the_actual_textbox):
        """
        Trigger effect after follower taking damage, unless it is destroyed by damage.
        """
        pass


    def recover_hp(self, heal_amount: int, game_state: SHCGGameState, draw_ui, set_text, the_actual_textbox,
                   healer: Card | None = None):
        """
        Recover HP for the follower. But not above max HP.
        """
        hp_before = self.hp
        self.hp = min(self.max_hp, self.hp + heal_amount)
        real_amount_healed = self.hp - hp_before
        if set_text:
            the_actual_textbox.append_html_text(f"{self}が{healer}によって{real_amount_healed}回復したのじゃ。\n")
        # if real_amount_healed > 0:
        #     print(f"{self} recovered {real_amount_healed} HP, current HP: {self.hp}/{self.max_hp}")


    def stats_change_effect(self, game_state: SHCGGameState, draw_ui, set_text, the_actual_textbox,
                             imposter: Card | None, attack_change: int, hp_change: int):
        """
        Handle generic stat changes effect like -1/-1, +2/+0, etc.
        Unlike take damage, max_hp is also affected by negative or positive hp changes.
        When hp <= 0, it is banished.
        Use simple version if not on field.
        """
        self.attack += attack_change
        self.hp += hp_change
        self.max_hp += hp_change
        for p in [1, 2]:
            if self in game_state.fields[p]:
                player = p
                break
        assert player in [1, 2], "Follower not found on any player's field."
        # make no sense for atk to be less than 0
        if self.attack < 0:
            self.attack = 0
        # clean up if hp goes below 0
        if self.hp <= 0:
            self.mv(game_state.fields[player], mode="banish", game_state=game_state, draw_ui=draw_ui, set_text=set_text, the_actual_textbox=the_actual_textbox, player=player)
        else:
            if set_text:
                the_actual_textbox.append_html_text(f"プレイヤー{player}の{self}のステータスが{imposter}によって変更されたのじゃ：")
                # +n/-nを正しく表示するのじゃ
                attack_str = f"+{attack_change}" if attack_change >= 0 else f"-{attack_change}"
                hp_str = f"+{hp_change}" if hp_change >= 0 else f"-{hp_change}"
                the_actual_textbox.append_html_text(f"{attack_str}/{hp_str}なのじゃ。\n")


    def stats_change_effect_simple(self, attack_change: int, hp_change: int, draw_ui, set_text, the_actual_textbox):
        """
        A simplified version of stats_change_effect. No need for game state.
        """
        assert hp_change >= 0, "Not supported in simple version."
        self.attack += attack_change
        self.hp += hp_change
        self.max_hp += hp_change
        # clean up if hp goes below 0
        if self.hp <= 0:
            pass
        if self.attack < 0:
            self.attack = 0
        if set_text:
            the_actual_textbox.append_html_text(f"{self}のステータスが変更されたのじゃ：")
            # +n/-nを正しく表示するのじゃ
            attack_str = f"+{attack_change}" if attack_change >= 0 else f"-{attack_change}"
            hp_str = f"+{hp_change}" if hp_change >= 0 else f"-{hp_change}"
            the_actual_textbox.append_html_text(f"{attack_str}/{hp_str}なのじゃ。\n")



    def __repr__(self):
        return f"{self.name}({self.attack}/{self.hp})"


