            if amount >= 0:
                the_actual_textbox.append_html_text(f"{self}のコストが{amount}増えたのじゃ。現在のコストは{self.cost}なのじゃ。\n")
            else:
                the_actual_textbox.append_html_text(f"{self}のコストが{-amount}減ったのじゃ。現在のコストは{self.cost}なのじゃ。\n")
        

