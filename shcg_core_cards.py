class Amulet(Card):
    def __init__(self, name, cost):
        super().__init__(name, cost, 'amulet')
        self.counter_name: str = ""  # name of the counter, e.g., "soul"
        self.counter: int = 0  # for amulets that have counters
        self.counter_max: int = 0  # maximum counter value for the amulet
        self.amulet_value_for_evaluate: int = self.cost * 4  # value used in AI evaluation of game state when on field
    
    def decrease_counter(self, amount: int =1):
        """
        Return True if counter reaches 0, else False.
        When reaches 0, must destroy. Otherwise, 白霜の風 will need update.
        """
        self.counter = max(0, self.counter - amount)
        if self.counter == 0:
            # amulet is destroyed when counter reaches 0
            # not handled here
            return True
        return False

    def destroy_amulet(self, game_state: SHCGGameState, draw_ui, set_text, the_actual_textbox, player: int):
        """
        Destroy this amulet on the field of the specified player.
        Usually called when counter reaches 0.
        """
        self.mv(game_state.fields[player], mode="destroy", game_state=game_state, draw_ui=draw_ui, set_text=set_text, the_actual_textbox=the_actual_textbox, player=player)

    def tooltip_str(self):
        s = f"<b>{self.name}</b>\n"
        c = "#070c55"
        if self.counter_name:
            s += f"<font color={c}>{self.counter_name}: {self.counter}</font>\n"
        if self.extra_tooltip_str:
            c = "#9900ff"
            s += f"<font color={c}>{self.extra_tooltip_str}</font>\n"
        if self.effect_description:
            c = "#6c6cff"
            s += f"<font color={c}>{self.effect_description}</font>\n"
        if self.description:
            s += f"{self.description}\n"
        return s

    def __repr__(self):
        return f"{self.name}"


